package com.sqlapk.medicine.module.system.service.errorcode;

import cn.hutool.core.collection.CollUtil;
import com.google.common.annotations.VisibleForTesting;
import com.sqlapk.medicine.framework.common.pojo.PageResult;
import com.sqlapk.medicine.module.system.api.errorcode.dto.ErrorCodeAutoGenerateReqDTO;
import com.sqlapk.medicine.module.system.api.errorcode.dto.ErrorCodeRespDTO;
import com.sqlapk.medicine.module.system.controller.admin.errorcode.vo.ErrorCodeCreateReqVO;
import com.sqlapk.medicine.module.system.controller.admin.errorcode.vo.ErrorCodeExportReqVO;
import com.sqlapk.medicine.module.system.controller.admin.errorcode.vo.ErrorCodePageReqVO;
import com.sqlapk.medicine.module.system.controller.admin.errorcode.vo.ErrorCodeUpdateReqVO;
import com.sqlapk.medicine.module.system.convert.errorcode.ErrorCodeConvert;
import com.sqlapk.medicine.module.system.dal.dataobject.errorcode.ErrorCodeDO;
import com.sqlapk.medicine.module.system.dal.mysql.errorcode.ErrorCodeMapper;
import com.sqlapk.medicine.module.system.enums.errorcode.ErrorCodeTypeEnum;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.validation.annotation.Validated;

import javax.annotation.Resource;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.stream.Collectors;
import com.sqlapk.medicine.framework.mybatis.core.query.LambdaQueryWrapperX;

import static com.sqlapk.medicine.framework.common.exception.util.ServiceExceptionUtil.exception;
import static com.sqlapk.medicine.framework.common.util.collection.CollectionUtils.convertSet;
import static com.sqlapk.medicine.module.system.enums.ErrorCodeConstants.ERROR_CODE_DUPLICATE;
import static com.sqlapk.medicine.module.system.enums.ErrorCodeConstants.ERROR_CODE_NOT_EXISTS;

/**
 * 错误码 Service 实现类
 *
 * @author dlyan
 */
@Service
@Validated
@Slf4j
public class ErrorCodeServiceImpl implements ErrorCodeService {

    @Resource
    private ErrorCodeMapper errorCodeMapper;

    @Override
    public Long createErrorCode(ErrorCodeCreateReqVO createReqVO) {
        // 校验 code 重复
        validateCodeDuplicate(createReqVO.getCode(), null);

        // 插入
        ErrorCodeDO errorCode = ErrorCodeConvert.INSTANCE.convert(createReqVO)
                .setType(ErrorCodeTypeEnum.MANUAL_OPERATION.getType());
        errorCodeMapper.insert(errorCode);
        // 返回
        return errorCode.getId();
    }

    @Override
    public void updateErrorCode(ErrorCodeUpdateReqVO updateReqVO) {
        // 校验存在
        validateErrorCodeExists(updateReqVO.getId());
        // 校验 code 重复
        validateCodeDuplicate(updateReqVO.getCode(), updateReqVO.getId());

        // 更新
        ErrorCodeDO updateObj = ErrorCodeConvert.INSTANCE.convert(updateReqVO)
                .setType(ErrorCodeTypeEnum.MANUAL_OPERATION.getType());
        errorCodeMapper.updateById(updateObj);
    }

    @Override
    public void deleteErrorCode(Long id) {
        // 校验存在
        validateErrorCodeExists(id);
        // 删除
        errorCodeMapper.deleteById(id);
    }

    /**
     * 校验错误码的唯一字段是否重复
     *
     * 是否存在相同编码的错误码
     *
     * @param code 错误码编码
     * @param id 错误码编号
     */
    @VisibleForTesting
    public void validateCodeDuplicate(Integer code, Long id) {
        ErrorCodeDO errorCodeDO = errorCodeMapper.selectByCode(code);
        if (errorCodeDO == null) {
            return;
        }
        // 如果 id 为空，说明不用比较是否为相同 id 的错误码
        if (id == null) {
            throw exception(ERROR_CODE_DUPLICATE);
        }
        if (!errorCodeDO.getId().equals(id)) {
            throw exception(ERROR_CODE_DUPLICATE);
        }
    }

    @VisibleForTesting
    void validateErrorCodeExists(Long id) {
        if (errorCodeMapper.selectById(id) == null) {
            throw exception(ERROR_CODE_NOT_EXISTS);
        }
    }

    @Override
    public ErrorCodeDO getErrorCode(Long id) {
        return errorCodeMapper.selectById(id);
    }

    @Override
    public PageResult<ErrorCodeDO> getErrorCodePage(ErrorCodePageReqVO pageReqVO) {
        return errorCodeMapper.selectPage(pageReqVO);
    }

    @Override
    public List<ErrorCodeDO> getErrorCodeList(ErrorCodeExportReqVO exportReqVO) {
        return errorCodeMapper.selectList(exportReqVO);
    }

    @Override
    @Transactional
    public void autoGenerateErrorCodes(List<ErrorCodeAutoGenerateReqDTO> autoGenerateDTOs) {
        if (CollUtil.isEmpty(autoGenerateDTOs)) {
            return;
        }
        // 按 applicationName 分组处理，避免不同应用间的错误码冲突
        Map<String, List<ErrorCodeAutoGenerateReqDTO>> groupedByApp = autoGenerateDTOs.stream()
                .collect(Collectors.groupingBy(ErrorCodeAutoGenerateReqDTO::getApplicationName));
        
        groupedByApp.forEach((applicationName, dtos) -> {
            // 获得该应用下的错误码（同时考虑 code 和 applicationName）
            Set<Integer> codes = convertSet(dtos, ErrorCodeAutoGenerateReqDTO::getCode);
            List<ErrorCodeDO> errorCodeDOs = errorCodeMapper.selectList(
                    new LambdaQueryWrapperX<ErrorCodeDO>()
                            .in(ErrorCodeDO::getCode, codes)
                            .eq(ErrorCodeDO::getApplicationName, applicationName));
            // 使用 code + applicationName 作为 key，确保唯一性
            Map<String, ErrorCodeDO> errorCodeDOMap = errorCodeDOs.stream()
                    .collect(Collectors.toMap(
                            e -> e.getCode() + ":" + e.getApplicationName(),
                            e -> e,
                            (e1, e2) -> e1));

            // 遍历该应用下的错误码，逐个插入或更新
            dtos.forEach(autoGenerateDTO -> {
                String key = autoGenerateDTO.getCode() + ":" + autoGenerateDTO.getApplicationName();
                ErrorCodeDO errorCodeDO = errorCodeDOMap.get(key);
                // 不存在，则进行新增
                if (errorCodeDO == null) {
                    errorCodeDO = ErrorCodeConvert.INSTANCE.convert(autoGenerateDTO)
                            .setType(ErrorCodeTypeEnum.AUTO_GENERATION.getType());
                    errorCodeMapper.insert(errorCodeDO);
                    return;
                }
                // 存在，则进行更新。更新有两个前置条件：
                // 条件 1. 只更新自动生成的错误码，即 Type 为 ErrorCodeTypeEnum.AUTO_GENERATION
                if (!ErrorCodeTypeEnum.AUTO_GENERATION.getType().equals(errorCodeDO.getType())) {
                    return;
                }
                // 条件 2. 错误提示语存在差异
                if (autoGenerateDTO.getMessage().equals(errorCodeDO.getMessage())) {
                    return;
                }
                // 最终匹配，进行更新
                errorCodeMapper.updateById(new ErrorCodeDO().setId(errorCodeDO.getId()).setMessage(autoGenerateDTO.getMessage()));
            });
        });
    }

    @Override
    public List<ErrorCodeRespDTO> getErrorCodeList(String applicationName, LocalDateTime minUpdateTime) {
        List<ErrorCodeDO> errorCodeDOs = errorCodeMapper.selectListByApplicationNameAndUpdateTimeGt(
                applicationName, minUpdateTime);
        return ErrorCodeConvert.INSTANCE.convertList03(errorCodeDOs);
    }

}

